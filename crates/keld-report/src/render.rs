fn html_escape(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            '\'' => out.push_str("&#39;"),
            _ => out.push(c),
        }
    }
    out
}

fn render_csv(doc: &ReportDocument) -> String {
    let mut out = String::from("id,severity,module,target,title,evidence,timestamp\n");
    for f in &doc.findings {
        out.push_str(&csv_field(&f.id));
        out.push(',');
        out.push_str(&csv_field(f.severity.as_str()));
        out.push(',');
        out.push_str(&csv_field(&f.module));
        out.push(',');
        out.push_str(&csv_field(&f.target));
        out.push(',');
        out.push_str(&csv_field(&f.title));
        out.push(',');
        out.push_str(&csv_field(&f.evidence));
        out.push(',');
        out.push_str(&csv_field(&f.timestamp));
        out.push('\n');
    }
    out
}

fn csv_field(s: &str) -> String {
    if s.contains([',', '"', '\n', '\r']) {
        format!("\"{}\"", s.replace('"', "\"\""))
    } else {
        s.to_string()
    }
}

fn sarif_level(severity: Severity) -> &'static str {
    match severity {
        Severity::Critical | Severity::High => "error",
        Severity::Medium => "warning",
        Severity::Low | Severity::Info => "note",
    }
}

fn sarif_message(title: &str, evidence: &str) -> String {
    if evidence.is_empty() {
        title.to_string()
    } else {
        format!("{title}: {evidence}")
    }
}

fn render_sarif(doc: &ReportDocument) -> Result<String, ReportError> {
    let mut rules = Vec::new();
    let mut rule_index = std::collections::BTreeMap::new();
    for f in &doc.findings {
        let rule_id = format!("{}/{}", f.module, slug(&f.id));
        if !rule_index.contains_key(&rule_id) {
            let idx = rules.len();
            rule_index.insert(rule_id.clone(), idx);
            rules.push(json!({
                "id": rule_id,
                "shortDescription": { "text": f.title },
                "fullDescription": { "text": if f.evidence.is_empty() { f.title.clone() } else { f.evidence.clone() } },
                "defaultConfiguration": { "level": sarif_level(f.severity) },
                "properties": {
                    "tags": ["security", f.module],
                    "problem.severity": f.severity.as_str(),
                }
            }));
        }
    }

    let mut results = Vec::new();
    for f in &doc.findings {
        let rule_id = format!("{}/{}", f.module, slug(&f.id));
        let idx = rule_index[&rule_id];
        let mut result = json!({
            "ruleId": rule_id,
            "ruleIndex": idx,
            "level": sarif_level(f.severity),
            "message": { "text": sarif_message(&f.title, &f.evidence) },
            "locations": [{
                "physicalLocation": {
                    "artifactLocation": { "uri": target_uri(&f.target) }
                }
            }],
            "properties": {
                "keld.severity": f.severity.as_str(),
                "keld.module": f.module,
                "keld.id": f.id,
            }
        });
        if !f.timestamp.is_empty() {
            result["properties"]["keld.timestamp"] = Value::String(f.timestamp.clone());
        }
        results.push(result);
    }

    let log = json!({
        "$schema": "https://json.schemastore.org/sarif-2.1.0.json",
        "version": "2.1.0",
        "runs": [{
            "tool": {
                "driver": {
                    "name": NAME,
                    "version": if doc.keld_version.is_empty() { VERSION } else { &doc.keld_version },
                    "informationUri": "https://github.com/Leo-Galli/keld",
                    "rules": rules,
                }
            },
            "results": results,
            "invocations": [{
                "executionSuccessful": true,
                "endTimeUtc": doc.generated_at,
            }],
        }]
    });
    Ok(serde_json::to_string_pretty(&log)?)
}

fn slug(s: &str) -> String {
    let mut out = String::new();
    for c in s.chars() {
        if c.is_ascii_alphanumeric() {
            out.push(c.to_ascii_lowercase());
        } else if !out.ends_with('-') {
            out.push('-');
        }
    }
    let trimmed = out.trim_matches('-').to_string();
    if trimmed.is_empty() {
        "finding".into()
    } else {
        trimmed
    }
}

fn target_uri(target: &str) -> String {
    if target.contains("://") {
        target.to_string()
    } else {
        format!("keld://target/{target}")
    }
}
